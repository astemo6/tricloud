let lang = null;
export function getLang() {
  if (lang) return lang;
  let l = "zh";
  try {
    const s = localStorage.getItem("tc_lang");
    if (s === "zh" || s === "en") l = s;
    else if (typeof navigator !== "undefined" && navigator.language && navigator.language.indexOf("en") === 0) l = "en";
  } catch (_) { /* 沙箱中无 localStorage */ }
  lang = l;
  return l;
}
export function setLang(l) {
  if (l !== "zh" && l !== "en") return;
  lang = l;
  try { localStorage.setItem("tc_lang", l); } catch (_) { /* ignore */ }
  if (typeof document !== "undefined") document.documentElement.lang = l === "en" ? "en" : "zh-CN";
}
export function t(key, vars) {
  const L = getLang();
  let s = (STR[L] && STR[L][key]) ?? STR.zh[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}
// 别名：局部变量名与 t 冲突的模块（tasks.js / guard.js 等）import { tr } 用
export const tr = t;
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
